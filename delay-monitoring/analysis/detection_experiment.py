def plot_detection_per_dist(dist, results_by_level, n_test, n_reconstruct):
    """
    TVD vs cumulative sample count for each loaded CT level against the
    ct_00 reference. Detection threshold Delta and the detection points
    are marked. A shaded region shows the n_reconstruct window needed
    after the earliest detection.
    """
    fig, ax = plt.subplots(figsize=(10, 5))

    earliest_detection = None
    all_ns = []

    for ct_label in ["ct_20", "ct_40", "ct_60", "ct_80"]:
        results, detected_at = results_by_level[ct_label]
        if not results:
            continue

        ns, tvds = zip(*results)
        all_ns.extend(ns)
        ct_pct   = ct_label.replace("ct_0", "").replace("ct_", "") + "%"
        label    = f"CT {ct_pct}"
        if detected_at is not None:
            label += f"  — detected at n = {detected_at:,}"
        else:
            label += "  — not detected"

        ax.plot(ns, tvds, color=CT_COLORS[ct_label], linewidth=2.0,
                marker="o", markersize=5, label=label)

        if detected_at is not None:
            ax.axvline(x=detected_at, color=CT_COLORS[ct_label],
                       linestyle=":", linewidth=1.2, alpha=0.7)
            if earliest_detection is None or detected_at < earliest_detection:
                earliest_detection = detected_at

    # lock x-axis to the data range so reconstruction window doesn't blow the scale
    if all_ns:
        ax.set_xlim(0, max(all_ns) * 1.05)

    # annotate n_reconstruct as a text note rather than a shaded span
    if earliest_detection is not None:
        ax.annotate(
            f"n_reconstruct = {n_reconstruct:,}\n(needed after detection)",
            xy=(earliest_detection, DELTA),
            xytext=(earliest_detection + (max(all_ns) * 0.05), DELTA * 1.3),
            fontsize=8, color="#555555",
            arrowprops=dict(arrowstyle="->", color="#555555", lw=0.8)
        )

    ax.axhline(y=DELTA, color="black", linestyle="--", linewidth=1.5,
               label=f"Detection threshold Δ = {DELTA}")

    ax.set_xlabel("Cumulative samples since load change")
    ax.set_ylabel("TVD (reference P vs empirical Q)")
    ax.set_title(
        f"{DIST_LABELS[dist]} — identity testing under cross-traffic load change\n"
        f"Reference: 0% CT baseline  |  n_test = {n_test:,}  |  "
        f"Δ = {DELTA},  ε = {EPSILON}",
        fontsize=10
    )
    ax.legend(fontsize=8)
    ax.grid(True, alpha=0.3)

    plt.tight_layout()
    out = os.path.join(RESULTS_DIR, f"detection_{dist}.png")
    plt.savefig(out, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  Saved: {out}")


def plot_detection_summary(all_results, n_test):
    """
    Samples to detection vs cross-traffic level, for each distribution.
    Bars show how many samples the identity tester needed before firing.
    'Not detected' levels are omitted.
    """
    dist_colors = {"normal": "#3498db", "lognormal": "#e74c3c", "weibull": "#2ecc71"}
    loaded_labels = ["ct_20", "ct_40", "ct_60", "ct_80"]
    loaded_pcts   = [20, 40, 60, 80]

    fig, ax = plt.subplots(figsize=(9, 5))
    fig.suptitle(
        f"Samples to detection vs cross-traffic level\n"
        f"n_test = {n_test:,}  |  Δ = {DELTA}  |  ε = {EPSILON}",
        fontsize=11
    )

    width   = 6
    offsets = [-width, 0, width]

    for dist, offset in zip(DISTS, offsets):
        det_counts = []
        x_positions = []
        for pct, ct_label in zip(loaded_pcts, loaded_labels):
            _, detected_at = all_results[dist][ct_label]
            if detected_at is not None:
                det_counts.append(detected_at)
                x_positions.append(pct + offset)

        if det_counts:
            ax.bar(x_positions, det_counts, width=width * 0.85,
                   color=dist_colors[dist], alpha=0.85,
                   label=DIST_LABELS[dist])

    ax.axhline(y=n_test, color="black", linestyle="--", linewidth=1.2,
               label=f"One test window (n_test = {n_test:,})")

    ax.set_xlabel("Cross-traffic utilisation (%)")
    ax.set_ylabel("Samples to detection")
    ax.set_xticks(loaded_pcts)
    ax.set_xticklabels([f"{p}%" for p in loaded_pcts])
    ax.legend(fontsize=8)
    ax.grid(True, alpha=0.3, axis="y")

    plt.tight_layout()
    out = os.path.join(RESULTS_DIR, "detection_summary.png")
    plt.savefig(out, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  Saved: {out}")


# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------

def run():
    os.makedirs(RESULTS_DIR, exist_ok=True)

    n_test        = n_test_formula()
    n_reconstruct = n_reconstruct_formula()

    print("=" * 65)
    print("Detection experiment — identity testing (cross-traffic)")
    print("=" * 65)
    print(f"  k              : {K}  ({BIN_SIZE}ms bins, 0–{int(GRID_MAX)}ms)")
    print(f"  Delta          : {DELTA}  (minimum detectable TVD shift)")
    print(f"  epsilon        : {EPSILON}  (99% confidence)")
    print(f"  n_test         : {n_test:,}")
    print(f"  n_reconstruct  : {n_reconstruct:,}  (after detection)")
    print()

    # all_results[dist][ct_label] = (results_list, detected_at)
    all_results = {d: {} for d in DISTS}

    header = (f"  {'dist':<12} {'CT level':>10}  {'true TVD':>10}  "
              f"{'detected at n':>15}  {'windows':>8}")
    print(header)
    print("  " + "-" * (len(header) - 2))

    for dist in DISTS:
        baseline_samples = load_samples(dist, "ct_00")
        reference_pmf    = empirical_pmf(baseline_samples)

        for ct_label, ct_name in zip(CT_LABELS, CT_NAMES):
            samples  = load_samples(dist, ct_label)
            loaded_pmf = empirical_pmf(samples)
            true_tvd   = tvd(reference_pmf, loaded_pmf)

            if ct_label == "ct_00":
                all_results[dist][ct_label] = ([], None)
                d_col = dist
                print(f"  {d_col:<12} {ct_name:>10}  {true_tvd:>10.4f}  "
                      f"{'(reference)':>15}  {'—':>8}")
                continue

            results, detected_at = run_detection(reference_pmf, samples, n_test)
            all_results[dist][ct_label] = (results, detected_at)

            det_str = f"{detected_at:,}" if detected_at is not None else "not detected"
            windows = len(results)
            d_col   = ""
            print(f"  {d_col:<12} {ct_name:>10}  {true_tvd:>10.4f}  "
                  f"{det_str:>15}  {windows:>8}")

        print()

    print("Generating plots...")
    for dist in DISTS:
        plot_detection_per_dist(dist, all_results[dist], n_test, n_reconstruct)

        # distribution overlay: reference vs each loaded CT level
        baseline_samples = load_samples(dist, "ct_00")
        ref_pmf          = empirical_pmf(baseline_samples)
        phase_pmfs       = [("Before (0% CT — reference)", "#2d3436", ref_pmf)]
        for ct_label, ct_name in zip(CT_LABELS[1:], CT_NAMES[1:]):
            loaded_pmf = empirical_pmf(load_samples(dist, ct_label))
            phase_pmfs.append((f"After load change (CT {ct_name})",
                               CT_COLORS[ct_label], loaded_pmf))
        plot_phase_distributions(
            dist, phase_pmfs,
            title=(f"{DIST_LABELS[dist]} — delay distribution before and after load change\n"
                   f"n = {N_SAMPLES:,} samples per phase"),
            out_path=os.path.join(RESULTS_DIR, f"distributions_{dist}.png")
        )

    plot_detection_summary(all_results, n_test)
    print("Done.")


# ---------------------------------------------------------------------------
# changeover pipeline (single continuous stream)
