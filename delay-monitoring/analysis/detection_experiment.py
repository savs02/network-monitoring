def load_changeover_samples(dist, ct_label):
    path = os.path.join(CHANGEOVER_DIR, dist, ct_label, "delay_samples.csv")
    return pd.read_csv(path)["delay_ms"].values


def plot_changeover(dist, ct_label, tvd_results, detected_at, n_test, n_reconstruct):
    """
    TVD vs cumulative samples for a single continuous stream.
    The reference is built from the first N_BEFORE samples; the detection
    stream starts immediately after. The changeover point and detection
    point are both marked, along with the reconstruction window.
    """
    ct_pct = ct_label.replace("ct_", "") + "%"

    fig, ax = plt.subplots(figsize=(11, 5))

    if tvd_results:
        ns, tvds = zip(*tvd_results)
        # offset by N_BEFORE so the curve sits on the same total-packet-count axis
        # as the vertical markers
        ns_total = [n + N_BEFORE for n in ns]
        ax.plot(ns_total, tvds, color=CT_COLORS.get(ct_label, "#636e72"),
                linewidth=2.0, marker="o", markersize=5,
                label=f"TVD vs reference  (CT {ct_pct})")

    # mark end of reference phase and actual CT start (which is ~10% later)
    ax.axvline(x=N_BEFORE, color="#636e72", linestyle="-.", linewidth=1.0,
               label=f"Reference phase ends  (n = {N_BEFORE:,})")
    ax.axvline(x=N_CHANGEOVER, color="black", linestyle="-.", linewidth=1.2,
               label=f"Cross-traffic starts  (~n = {N_CHANGEOVER:,})")

    if detected_at is not None:
        detection_total = N_BEFORE + detected_at
        ax.axvline(x=detection_total, color="#d63031",
                   linestyle=":", linewidth=1.5,
                   label=f"Detection  (n = {detection_total:,}, "
                         f"+{detected_at - (N_CHANGEOVER - N_BEFORE):,} after CT start)")
        ax.axvspan(detection_total, detection_total + n_reconstruct,
                   alpha=0.07, color="grey",
                   label=f"Reconstruction window (n = {n_reconstruct:,})")

    ax.axhline(y=DELTA, color="black", linestyle="--", linewidth=1.5,
               label=f"Detection threshold Δ = {DELTA}")

    ax.set_xlabel("Cumulative probe packet count")
    ax.set_ylabel("TVD (reference P vs empirical Q)")
    ax.set_title(
        f"{DIST_LABELS[dist]} — before / detection / reconstruction pipeline\n"
        f"CT {ct_pct}  |  n_test = {n_test:,}  |  Δ = {DELTA},  ε = {EPSILON}",
        fontsize=10
    )
    ax.legend(fontsize=8)
    ax.grid(True, alpha=0.3)

    plt.tight_layout()
    out = os.path.join(RESULTS_DIR, f"changeover_{dist}_{ct_label}.png")
    plt.savefig(out, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  Saved: {out}")


def run_changeover():
    """
    Analyse the single-stream changeover data from run_detection_experiment.sh.
    """
    os.makedirs(RESULTS_DIR, exist_ok=True)

    n_test        = n_test_formula()
    n_reconstruct = n_reconstruct_formula()

    print("=" * 65)
    print("Detection experiment — changeover pipeline")
    print("=" * 65)
    print(f"  N_BEFORE      : {N_BEFORE:,}  (reference phase)")
    print(f"  n_test        : {n_test:,}")
    print(f"  n_reconstruct : {n_reconstruct:,}")
    print(f"  Δ = {DELTA},  ε = {EPSILON}")
    print()

    loaded_labels = ["ct_20", "ct_40", "ct_60", "ct_80"]

    header = (f"  {'dist':<12} {'CT level':>10}  {'detected +n':>12}  "
              f"{'samples left':>14}")
    print(header)
    print("  " + "-" * (len(header) - 2))

    for dist in DISTS:
        for ct_label in loaded_labels:
            all_samples   = load_changeover_samples(dist, ct_label)
            before_samples = all_samples[:N_BEFORE]
            after_samples  = all_samples[N_BEFORE:]

            reference_pmf = empirical_pmf(before_samples)

            results, detected_at = run_detection(reference_pmf, after_samples, n_test)

            samples_left = len(after_samples) - detected_at if detected_at else 0
            det_str      = f"+{detected_at:,}" if detected_at is not None else "not detected"
            d_col        = dist if ct_label == loaded_labels[0] else ""
            ct_pct       = ct_label.replace("ct_", "") + "%"

            print(f"  {d_col:<12} {ct_pct:>10}  {det_str:>12}  {samples_left:>14,}")

            plot_changeover(dist, ct_label, results, detected_at,
                            n_test, n_reconstruct)

            # distribution overlay for this CT level
            phase_pmfs = [("Before — reference P", "#2d3436", reference_pmf)]
            if detected_at is not None:
                post_det = after_samples[detected_at:]
                if len(post_det) > 0:
                    phase_pmfs.append((
                        f"Post-detection — new distribution Q "
                        f"({len(post_det):,} samples)",
                        CT_COLORS.get(ct_label, "#636e72"),
                        empirical_pmf(post_det)
                    ))
            else:
                phase_pmfs.append((
                    f"After CT {ct_pct} — not detected "
                    f"({len(after_samples):,} samples)",
                    CT_COLORS.get(ct_label, "#636e72"),
                    empirical_pmf(after_samples)
                ))
            plot_phase_distributions(
                dist, phase_pmfs,
                title=(f"{DIST_LABELS[dist]} — distribution phases  |  CT {ct_pct}\n"
                       f"Before → detection window → post-detection"),
                out_path=os.path.join(RESULTS_DIR,
                                      f"distributions_changeover_{dist}_{ct_label}.png")
            )
        print()

    print("Done.")


if __name__ == "__main__":
    run()
