"""
Detection experiment — identity testing under cross-traffic load change.

Physical setup
--------------
A probe flow shares a 10 Mbps link with cross-traffic. At baseline (0% CT)
the monitor builds a reference distribution P. When cross-traffic comes on,
the experienced delay distribution shifts due to queuing. The detection phase
determines how many new samples are needed before the monitor can reliably
flag that the distribution has changed.

Three phases
------------
  1. Reference (before): build empirical PMF P from ct_00 (0% cross-traffic)
     using n_reconstruct samples.
  2. Detection: stream samples from the loaded level through an identity
     tester. Every n_test samples, compute TVD(P, Q_empirical). Flag
     detection when TVD > Delta.
  3. Reconstruction (post-detection): once detected, n_reconstruct further
     samples are needed to reconstruct the new distribution Q.

Identity testing sample complexity
-----------------------------------
    n_test = ceil( sqrt(k) / Delta^2  +  log(1/epsilon) / Delta^2 )

  k       = number of bins (support size of the discrete distribution)
  Delta   = minimum TVD shift to detect
  epsilon = failure probability

Reconstruction sample complexity
---------------------------------
    n_reconstruct = ceil( (k * log(1/epsilon)) / delta^2 )

  Same Delta and epsilon as the identity testing phase.

Two modes
---------
  batch      : uses separate before (ct_00) and after (ct_XX) files from the
               existing cross-traffic experiment. Validates the detector against
               known distributions.
  changeover : uses a single continuous sample stream where cross-traffic starts
               mid-run (generated by run_detection_experiment.sh). The first
               N_BEFORE samples form the reference; the rest are the detection
               stream. This is the realistic pipeline: the monitor does not know
               when the change occurred.

Results saved to: results/detection/
"""

import math
import os

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))

# ---------------------------------------------------------------------------
# parameters
# ---------------------------------------------------------------------------

BIN_SIZE  = 1       # ms
GRID_MAX  = 150.0
K         = int(GRID_MAX / BIN_SIZE)

# identity testing parameters
DELTA   = 0.1    # minimum TVD shift to detect
EPSILON = 0.01   # failure probability (99% confidence)


DISTS      = ["normal", "lognormal", "weibull"]
DIST_LABELS = {
    "normal":    "Normal",
    "lognormal": "Lognormal",
    "weibull":   "Weibull",
}

CT_LABELS  = ["ct_00", "ct_20", "ct_40", "ct_60", "ct_80"]
CT_NAMES   = ["0%", "20%", "40%", "60%", "80%"]
CT_COLORS  = {
    "ct_20": "#0984e3",
    "ct_40": "#00b894",
    "ct_60": "#fdcb6e",
    "ct_80": "#d63031",
}

N_SAMPLES   = 61199   # samples available per (dist, level)
N_BEFORE      = 61199           # reference phase length for changeover runs
N_CHANGEOVER  = int(N_BEFORE * 1.10)  # expected packet index when CT starts (~67,319)
                                       # matches CHANGE_TIME in run_detection_experiment.sh
SOURCE_DIR  = os.path.join(SCRIPT_DIR, "../results/cross-traffic")
CHANGEOVER_DIR = os.path.join(SCRIPT_DIR, "../results/detection-changeover")
RESULTS_DIR = os.path.join(SCRIPT_DIR, "../results/detection")

BIN_EDGES   = np.arange(0.0, GRID_MAX + BIN_SIZE, BIN_SIZE)
BIN_CENTRES = BIN_EDGES[:-1] + BIN_SIZE / 2.0


# ---------------------------------------------------------------------------
# theory
# ---------------------------------------------------------------------------

def n_test_formula():
    """Identity testing sample complexity."""
    return math.ceil(
        math.sqrt(K) / DELTA ** 2
        + math.log(1.0 / EPSILON) / DELTA ** 2
    )


def n_reconstruct_formula():
    """Distribution reconstruction sample complexity."""
    return math.ceil(
        (K + math.log(1.0 / EPSILON)) / DELTA ** 2
    )


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def load_samples(dist, ct_label):
    path = os.path.join(SOURCE_DIR, dist, ct_label, "delay_samples.csv")
    return pd.read_csv(path)["delay_ms"].values


def empirical_pmf(samples):
    """Raw empirical PMF — no smoothing, for honest TVD computation."""
    counts = np.zeros(K)
    idx    = np.floor(samples / BIN_SIZE).astype(int)
    valid  = (idx >= 0) & (idx < K)
    np.add.at(counts, idx[valid], 1)
    total = counts.sum()
    return counts / total if total > 0 else counts


def tvd(p, q):
    return 0.5 * float(np.sum(np.abs(p - q)))


# ---------------------------------------------------------------------------
# detection algorithm
# ---------------------------------------------------------------------------

def run_detection(reference_pmf, stream_samples, n_test):
    """
    Batch identity tester.

    Accumulates stream_samples in non-overlapping windows of n_test.
    After each complete window, computes TVD(reference, empirical Q).
    Flags detection at the first window where TVD > Delta.

    Returns:
      results     : list of (cumulative_n, tvd_value) at each window boundary
      detected_at : cumulative sample count at detection, or None
    """
    results      = []
    detected_at  = None
    counts       = np.zeros(K)
    window_count = 0

    for i, s in enumerate(stream_samples):
        idx = int(s / BIN_SIZE)
        if 0 <= idx < K:
            counts[idx] += 1
        window_count += 1

        if window_count == n_test:
            total    = counts.sum()
            emp      = counts / total if total > 0 else counts
            t        = tvd(reference_pmf, emp)
            n_so_far = i + 1
            results.append((n_so_far, t))

            if detected_at is None and t > DELTA:
                detected_at = n_so_far

            # reset accumulator for the next window
            counts       = np.zeros(K)
            window_count = 0

    return results, detected_at


# ---------------------------------------------------------------------------
# plotting helpers
# ---------------------------------------------------------------------------

def zoom_mask(pmfs):
    """Return a boolean mask over BIN_CENTRES covering where any PMF has mass."""
    combined = np.zeros(K)
    for p in pmfs:
        combined += p
    active = combined > 1e-4
    # pad a small margin either side
    idx = np.where(active)[0]
    lo  = max(0,   idx[0]  - 3)
    hi  = min(K-1, idx[-1] + 3)
    mask = np.zeros(K, dtype=bool)
    mask[lo:hi+1] = True
    return mask


def plot_phase_distributions(dist, phase_pmfs, title, out_path):
    """
    Overlay empirical PMFs from multiple monitoring phases on the same axes.

    phase_pmfs : list of (label, colour, pmf_array) tuples
    """
    mask = zoom_mask([p for _, _, p in phase_pmfs])
    x    = BIN_CENTRES[mask]

    fig, ax = plt.subplots(figsize=(10, 5))

    for label, color, pmf in phase_pmfs:
        ax.plot(x, pmf[mask], color=color, linewidth=2.0, label=label)

    ax.set_xlabel("Delay (ms)")
    ax.set_ylabel("Probability mass per 1ms bin")
    ax.set_title(title, fontsize=10)
    ax.legend(fontsize=9)
    ax.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  Saved: {out_path}")


