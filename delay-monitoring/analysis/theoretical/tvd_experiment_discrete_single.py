"""
TVD experiment — discrete distributions, theoretical mode (single seed).

Reads the CSVs generated by run_sample_complexity_discrete.sh.
Produces a line plot of TVD vs n for each distribution.

Distributions:
  - Binomial(N=20, p=0.5)
  - Zipf(N=20, alpha=1.5)
  - Piecewise (irregular multi-modal, k=20)

Note: KS test is not applied to discrete distributions because scipy.stats.kstest
is designed for continuous distributions.  For a discrete CDF, D_n converges to
max_k P(X=k) rather than 0, making the statistic uninformative.
"""

import math
import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy import stats

# ---------------------------------------------------------------------------
# parameters
# ---------------------------------------------------------------------------

EPSILON = 0.05
DELTA   = 0.05

SCRIPT_DIR  = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR = os.path.join(SCRIPT_DIR, "../../results/sample-complexity/discrete/theoretical/single_seed")

DISTRIBUTIONS = {
    "binomial": {
        "label":        "Binomial(N=20, p=0.5)",
        "color":        "#9b59b6",
        "support":      np.arange(0, 21),
        "k":            21,
        "true_pmf":     lambda support: stats.binom.pmf(support, n=20, p=0.5),
        # n_theory = ceil((21 + ln(1/0.05)) / 0.05^2) = 9599
        "n_theory":     9599,
        "sample_sizes": [480, 960, 2400, 4800, 9599, 19197, 38393],
    },
    "zipf": {
        "label":        "Zipf(N=20, alpha=1.5)",
        "color":        "#e67e22",
        "support":      np.arange(1, 21),
        "k":            20,
        "true_pmf":     lambda support: stats.zipfian.pmf(support, a=1.5, n=20),
        # n_theory = ceil((20 + ln(1/0.05)) / 0.05^2) = 9199
        "n_theory":     9199,
        "sample_sizes": [460, 920, 2300, 4599, 9199, 18397, 36793],
    },
    "piecewise": {
        "label":        "Piecewise (irregular multi-modal)",
        "color":        "#27ae60",
        "support":      np.arange(1, 21),
        "k":            20,
        "true_pmf":     lambda support: np.array([
                            0.12, 0.02, 0.08, 0.01, 0.10, 0.03, 0.07, 0.12, 0.02, 0.09,
                            0.01, 0.08, 0.04, 0.06, 0.02, 0.05, 0.02, 0.04, 0.01, 0.01
                        ]),
        # n_theory = ceil((20 + ln(1/0.05)) / 0.05^2) = 9199
        "n_theory":     9199,
        "sample_sizes": [460, 920, 2300, 4599, 9199, 18397, 36793],
    },
}


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def load_samples(dist_name, n):
    filepath = os.path.join(RESULTS_DIR, f"delay_samples_{dist_name}_{n}.csv")
    raw = pd.read_csv(filepath)["delay_ms"].values
    return np.round(raw).astype(int)


def empirical_pmf(samples, support):
    counts = np.zeros(len(support))
    lo, hi = support[0], support[-1]
    for val in samples:
        if lo <= val <= hi:
            counts[val - lo] += 1
    total = counts.sum()
    return counts / total if total > 0 else counts


def tvd(p, q):
    return 0.5 * float(np.sum(np.abs(p - q)))


def theoretical_bound(n, n_theory):
    return min(1.0, DELTA * math.sqrt(n_theory / n))


# ---------------------------------------------------------------------------
# plotting
# ---------------------------------------------------------------------------

def plot_distribution(emp_pmf, true_pmf_vals, support, dist_config, n, tvd_val):
    fig, ax = plt.subplots(figsize=(9, 4))

    bar_width = 0.35
    ax.bar(support - bar_width / 2, emp_pmf, width=bar_width,
           color=dist_config["color"], alpha=0.7,
           label=f"Empirical PMF (n={n:,})")
    ax.bar(support + bar_width / 2, true_pmf_vals, width=bar_width,
           color="black", alpha=0.5, label="True PMF")

    ax.set_title(f"{dist_config['label']} — n = {n:,}\nTVD = {tvd_val:.6f}")
    ax.set_xlabel("Delay (ms, integer-valued)")
    ax.set_ylabel("Probability")
    ax.set_xticks(support)
    ax.legend(fontsize=8)
    ax.grid(True, alpha=0.3, axis="y")

    dist_name = [k for k, v in DISTRIBUTIONS.items() if v is dist_config][0]
    output_path = os.path.join(RESULTS_DIR, f"dist_{dist_name}_n{n}.png")
    plt.tight_layout()
    plt.savefig(output_path, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  Saved: {output_path}")


def plot_tvd_vs_n(results):
    fig, ax = plt.subplots(figsize=(10, 6))

    for dist_name, (dist_config, ns, tvd_vals) in results.items():
        n_theory = dist_config["n_theory"]
        bounds   = [theoretical_bound(n, n_theory) for n in ns]

        ax.plot(ns, tvd_vals, "o-", color=dist_config["color"],
                linewidth=2, markersize=7, label=dist_config["label"])
        ax.plot(ns, bounds, "--", color=dist_config["color"],
                linewidth=1.2, alpha=0.6,
                label=f"Bound — {dist_config['label']} ($n_{{theory}}={n_theory:,}$)")

    ax.axhline(y=DELTA, color="red", linestyle=":", linewidth=1.2,
               label=f"TVD = {DELTA} (accuracy target)")

    ax.set_xlabel("Number of samples (n)")
    ax.set_ylabel("Total Variation Distance")
    ax.set_title("TVD vs n — discrete distributions (single seed)")
    ax.legend(fontsize=8)
    ax.grid(True, alpha=0.3)

    output_path = os.path.join(RESULTS_DIR, "tvd_discrete_single.png")
    plt.tight_layout()
    plt.savefig(output_path, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  Saved: {output_path}")


# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------

def run():
    os.makedirs(RESULTS_DIR, exist_ok=True)

    print(f"{'Distribution':<25} {'n':>8} {'TVD':>10}")
    print("-" * 46)

    results = {}

    for dist_name, dist_config in DISTRIBUTIONS.items():
        support       = dist_config["support"]
        true_pmf_vals = dist_config["true_pmf"](support)
        sample_sizes  = dist_config["sample_sizes"]

        ns       = []
        tvd_vals = []
        first    = True

        for n in sample_sizes:
            samples = load_samples(dist_name, n)
            emp     = empirical_pmf(samples, support)
            tvd_val = tvd(true_pmf_vals, emp)

            label = dist_config["label"] if first else ""
            print(f"{label:<25} {n:>8,} {tvd_val:>10.6f}")
            first = False

            plot_distribution(emp, true_pmf_vals, support, dist_config, n, tvd_val)

            ns.append(n)
            tvd_vals.append(tvd_val)

        results[dist_name] = (dist_config, ns, tvd_vals)
        print()

    plot_tvd_vs_n(results)


if __name__ == "__main__":
    run()
